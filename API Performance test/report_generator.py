def _config_section_html(description: str, config_data: Optional[Dict]) -> str:
    """Render a 'Test Configuration' key-value table from config_data."""
    rows: List[tuple] = []

    if description:
        rows.append(("Description", description.replace("\n", "<br>")))

    if config_data:
        api_cfg = config_data.get("api", {})
        test_cfg = config_data.get("test", {})

        if api_cfg.get("base_url"):
            rows.append(("Base URL", api_cfg["base_url"]))
        rows.append(("User Count", str(test_cfg.get("user_count", "—"))))
        run_mode = str(test_cfg.get("run_mode", "—"))
        rows.append(("Run Mode", run_mode))
        if run_mode.strip().lower() == "single_journey":
            rows.append(("Iterations (per user)", str(test_cfg.get("iterations", "—"))))
        else:
            rows.append(("Run Time", str(test_cfg.get("run_time", "—"))))
        rows.append(("Spawn Rate", str(test_cfg.get("spawn_rate", "—"))))
        rows.append((
            "Think Time (page transition)",
            f"{test_cfg.get('think_time_min', '—')}s – {test_cfg.get('think_time_max', '—')}s",
        ))
        rows.append((
            "Think Time (WAFR batches)",
            f"{test_cfg.get('wafr_think_time_min', '—')}s – {test_cfg.get('wafr_think_time_max', '—')}s",
        ))
        rows.append(("Timeout (per request)", f"{api_cfg.get('timeout_seconds', '—')}s"))
        rows.append(("Users CSV", str(test_cfg.get("users_csv", "—"))))

    if not rows:
        return ""

    tbody = "".join(
        f"<tr><td>{k}</td><td>{v}</td></tr>"
        for k, v in rows
    )
    return (
        "<section>"
        '<div class="section-title" style="border-left-color:#64748b;background:#f8fafc;color:#1a2b3c;">'
        "Test Configuration</div>"
        '<div class="table-wrap">'
        f'<table class="config-tbl"><tbody>{tbody}</tbody></table>'
        "</div></section>"
    )


def _full_html(
    generated_at: str,
    stats_csv: Path,
    auth_rows: List[Dict],
    home_rows: List[Dict],
    wafr_rows: List[Dict],
    health_rows: List[Dict],
    chat_rows: List[Dict],
    aggregated_row: Optional[Dict],
    description: str = "",
    config_data: Optional[Dict] = None,
) -> str:
    all_rows = auth_rows + home_rows + wafr_rows + health_rows + chat_rows
    overall = _summary_totals(all_rows)
    hp_sum  = _summary_totals(home_rows)
    wafr_sum = _summary_totals(wafr_rows)
    auth_sum = _summary_totals(auth_rows)
    health_sum = _summary_totals(health_rows)
    chat_sum = _summary_totals(chat_rows)

    duration_s = _duration_from_aggregated(aggregated_row)

    # Duration / throughput derived from Aggregated row
    if duration_s is not None:
        m, sec = divmod(int(duration_s), 60)
        dur_str = f"{m}m {sec:02d}s" if m else f"{sec}s"
        total_reqs = sum(int(r.get(_COL_REQS, 0) or 0) for r in all_rows)
        total_fails = sum(int(r.get(_COL_FAILS, 0) or 0) for r in all_rows)
        total_rps   = total_reqs / duration_s
        success_rps = (total_reqs - total_fails) / duration_s
        tp_str = f"{total_rps:.2f} req/s"
        stp_str = f"{success_rps:.2f} req/s"
    else:
        dur_str = "—"
        tp_str  = "—"
        stp_str = "—"

    cards_html = "".join([
        _card("Total Requests",        overall["reqs"],  f"failures: {overall['fails']} ({overall['fail_pct']})"),
        _card("Test Duration",         dur_str,          f"total throughput: {tp_str}"),
        _card("Throughput",            tp_str,           f"successful: {stp_str}"),
        _card("Avg Response Time",     overall["avg_rt"], "across all endpoints"),
        _card("Home Page",             hp_sum["reqs"],   f"avg {hp_sum['avg_rt']} · {hp_sum['fail_pct']} fail"),
        _card("WAFR Page",             wafr_sum["reqs"], f"avg {wafr_sum['avg_rt']} · {wafr_sum['fail_pct']} fail"),
        _card("Health Events",         health_sum["reqs"], f"avg {health_sum['avg_rt']} · {health_sum['fail_pct']} fail"),
        _card("Chat",                  chat_sum["reqs"], f"avg {chat_sum['avg_rt']} · {chat_sum['fail_pct']} fail"),
    ])

    def _section(title: str, css_class: str, rows: List[Dict], empty: str) -> str:
        badge = f'<span class="badge">{len(rows)} endpoint{"s" if len(rows) != 1 else ""}</span>'
        totals = _summary_totals(rows)
        meta = (
            f" &nbsp;·&nbsp; {totals['reqs']} reqs &nbsp;·&nbsp; "
            f"avg {totals['avg_rt']} &nbsp;·&nbsp; {totals['fail_pct']} failures"
            if rows else ""
        )
        return (
            f"<section>"
            f'<div class="section-title {css_class}">{title} {badge}{meta}</div>'
            f"{_table_html(rows, empty)}"
            f"</section>"
        )

    desc_html = f'<div class="test-desc">{description}</div>' if description else ""
    config_html = _config_section_html(description, config_data)

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>MontyCloud API Performance Report</title>
<style>{_CSS}</style>
</head>
<body>
<header>
  <h1>MontyCloud API Performance Report</h1>
  <p>Generated: {generated_at} &nbsp;|&nbsp; Source: {stats_csv.name}</p>
  {desc_html}
</header>
<main>
    <div class="cards">{cards_html}</div>
    {_throughput_section_html(auth_rows, home_rows, wafr_rows, health_rows, chat_rows, duration_s)}
  {_critical_failures_section_html(all_rows)}
  {_section("Authentication", "auth", auth_rows, "No [Auth] data found.")}
  {_section("Home Page", "",     home_rows, "No [HomePage] data found.")}
  {_section("WAFR Page", "wafr", wafr_rows, "No [WAFR] data found.")}
  {_section("Health Events", "health", health_rows, "No [Health] data found.")}
  {_section("Chat", "chat", chat_rows, "No [Chat] data found.")}
  {config_html}
</main>
<footer>MontyCloud Performance Testing Framework &nbsp;·&nbsp; {generated_at}</footer>
</body>
</html>"""


