"""
Custom HTML Report Generator
==============================
Reads Locust's CSV stats output and produces a styled multi-section HTML report:

  Section 1 – Authentication endpoints  (prefix: [Auth])
  Section 2 – Home Page endpoints       (prefix: [HomePage])
  Section 3 – WAFR Page endpoints       (prefix: [WAFR])
  Section 4 – Health Events endpoints   (prefix: [Health])
  Section 5 – Chat endpoints            (prefix: [Chat])

The report is auto-generated by locustfile.py's test_stop hook when --csv is
passed to Locust.  It can also be run standalone:

    python report_generator.py --csv reports/stats_stats.csv
    python report_generator.py --csv reports/stats_stats.csv --output reports/my_report.html
"""

