import csv
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional

# Reports are written here unless the caller provides an explicit output path.
_REPORTS_DIR = Path(__file__).parent / "reports"

# ---------------------------------------------------------------------------
# Locust CSV column names (Locust 2.x)
# ---------------------------------------------------------------------------
_COL_NAME = "Name"
_COL_TYPE = "Type"
_COL_REQS = "Request Count"
_COL_FAILS = "Failure Count"
_COL_AVG = "Average Response Time"
_COL_MIN = "Min Response Time"
_COL_MAX = "Max Response Time"
_COL_MEDIAN = "Median Response Time"
_COL_P90 = "90%"
_COL_P95 = "95%"
_COL_P99 = "99%"
_COL_SIZE = "Average Content Size"
_COL_RPS = "Requests/s"
_COL_FPS = "Failures/s"


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _fmt(val: str, decimals: int = 1) -> str:
    """Format a numeric string; return the raw value or '—' if absent/zero."""
    if val is None or val == "":
        return "—"
    try:
        f = float(val)
        return f"{f:,.{decimals}f}"
    except (ValueError, TypeError):
        return str(val)


def _fail_pct(row: Dict[str, str]) -> str:
    try:
        reqs = int(row.get(_COL_REQS, 0) or 0)
        fails = int(row.get(_COL_FAILS, 0) or 0)
        if reqs == 0:
            return "0.0 %"
        return f"{fails / reqs * 100:.1f} %"
    except Exception:
        return "—"


def _weighted_avg_rt(rows: List[Dict[str, str]]) -> float:
    """Request-count-weighted average response time across stat rows.

    A plain mean of the per-endpoint averages would let an endpoint with 20
    requests count as much as one with 400; weighting by request count gives
    the true average over all individual requests.
    """
    weighted_sum = 0.0
    total = 0
    for r in rows:
        if not r.get(_COL_AVG):
            continue
        count = int(r.get(_COL_REQS, 0) or 0)
        weighted_sum += float(r[_COL_AVG]) * count
        total += count
    return weighted_sum / total if total else 0.0


def _summary_totals(rows: List[Dict[str, str]]) -> Dict[str, str]:
    """Compute aggregate totals across a list of stat rows."""
    total_reqs = sum(int(r.get(_COL_REQS, 0) or 0) for r in rows)
    total_fails = sum(int(r.get(_COL_FAILS, 0) or 0) for r in rows)
    avg_rt = _weighted_avg_rt(rows)
    fail_pct = f"{total_fails / total_reqs * 100:.1f} %" if total_reqs else "0.0 %"
    return {
        "reqs": f"{total_reqs:,}",
        "fails": f"{total_fails:,}",
        "fail_pct": fail_pct,
        "avg_rt": f"{avg_rt:,.1f} ms",
    }


def _duration_from_aggregated(aggregated: Optional[Dict[str, str]]) -> Optional[float]:
    """Derive test duration (seconds) from the Aggregated row: duration = reqs / req/s."""
    if not aggregated:
        return None
    try:
        reqs = float(aggregated.get(_COL_REQS, 0) or 0)
        rps = float(aggregated.get(_COL_RPS, 0) or 0)
        return reqs / rps if rps > 0 else None
    except Exception:
        return None


# Critical-issue thresholds
_CRIT_FAIL_PCT = 50.0    # endpoints with failure rate >= this are highlighted
_CRIT_AVG_MS   = 20_000  # endpoints with avg response >= this are highlighted


# ---------------------------------------------------------------------------
# HTML builders
# ---------------------------------------------------------------------------

_TABLE_HEADERS = [
    ("Endpoint", _COL_NAME),
    ("# Requests", _COL_REQS),
    ("# Failures", _COL_FAILS),
    ("Failure %", None),           # computed
    ("Avg (ms)", _COL_AVG),
    ("Min (ms)", _COL_MIN),
    ("Max (ms)", _COL_MAX),
    ("Median (ms)", _COL_MEDIAN),
    ("p90 (ms)", _COL_P90),
    ("p95 (ms)", _COL_P95),
    ("p99 (ms)", _COL_P99),
    ("Avg Size (B)", _COL_SIZE),
    ("Req/s", _COL_RPS),
    ("Fail/s", _COL_FPS),
]


def _table_html(rows: List[Dict[str, str]], empty_msg: str = "No data.") -> str:
    if not rows:
        return f'<p class="empty">{empty_msg}</p>'

    thead = "".join(f"<th>{h}</th>" for h, _ in _TABLE_HEADERS)
    tbody_rows: List[str] = []

    for row in rows:
        fail_count = int(row.get(_COL_FAILS, 0) or 0)
        cells: List[str] = []
        for header, col_key in _TABLE_HEADERS:
            if col_key is None:  # computed columns
                if header == "Failure %":
                    val = _fail_pct(row)
                    css = ' class="fail"' if fail_count > 0 else ""
                    cells.append(f"<td{css}>{val}</td>")
                    continue
            raw = row.get(col_key, "") if col_key else ""
            if col_key == _COL_NAME:
                cells.append(f"<td class='name'>{raw}</td>")
            elif col_key in (_COL_REQS, _COL_FAILS):
                cells.append(f"<td>{_fmt(raw, 0)}</td>")
            else:
                cells.append(f"<td>{_fmt(raw)}</td>")
        tbody_rows.append(f"<tr>{''.join(cells)}</tr>")

    return (
        '<div class="table-wrap">'
        f"<table><thead><tr>{thead}</tr></thead>"
        f"<tbody>{''.join(tbody_rows)}</tbody></table>"
        "</div>"
    )


def _card(label: str, value: str, sub: str = "") -> str:
    sub_html = f'<div class="sub">{sub}</div>' if sub else ""
    return (
        f'<div class="card">'
        f'<div class="card-label">{label}</div>'
        f'<div class="card-value">{value}</div>'
        f"{sub_html}"
        f"</div>"
    )


def _throughput_section_html(
    auth_rows: List[Dict],
    home_rows: List[Dict],
    wafr_rows: List[Dict],
    health_rows: List[Dict],
    chat_rows: List[Dict],
    duration_s: Optional[float],
) -> str:
    """Render the per-section throughput breakdown table."""

    def _stats(rows: List[Dict]):
        total = sum(int(r.get(_COL_REQS, 0) or 0) for r in rows)
        fails = sum(int(r.get(_COL_FAILS, 0) or 0) for r in rows)
        success = total - fails
        avg_rt = _weighted_avg_rt(rows)
        rps = f"{total / duration_s:.2f}" if duration_s else "—"
        srps = f"{success / duration_s:.2f}" if duration_s else "—"
        fp = fails / total * 100 if total else 0.0
        return total, fails, success, fp, rps, srps, avg_rt

    sections = [
        ("Authentication", "dot-auth",   auth_rows),
        ("Home Page",      "dot-home",   home_rows),
        ("WAFR Page",      "dot-wafr",   wafr_rows),
        ("Health Events",  "dot-health", health_rows),
        ("Chat",           "dot-chat",   chat_rows),
    ]
    tbody = ""
    for label, cls, rows in sections:
        t, f, s, fp, rps, srps, avg = _stats(rows)
        fcls = ' class="fail"' if f > 0 else ""
        tbody += (
            f"<tr>"
            f"<td><span class='{cls}'>●</span> {label}</td>"
            f"<td>{t:,}</td><td>{s:,}</td>"
            f"<td{fcls}>{f:,} ({fp:.1f} %)</td>"
            f"<td>{rps}</td><td>{srps}</td>"
            f"<td>{avg:,.0f} ms</td></tr>"
        )
    # Totals
    t, f, s, fp, rps, srps, avg = _stats(auth_rows + home_rows + wafr_rows + health_rows + chat_rows)
    fcls = ' class="fail"' if f > 0 else ""
    tbody += (
        f"<tr>"
        f"<td><span class='dot-total'>●</span> <strong>Total</strong></td>"
        f"<td><strong>{t:,}</strong></td><td><strong>{s:,}</strong></td>"
        f"<td{fcls}><strong>{f:,} ({fp:.1f} %)</strong></td>"
        f"<td><strong>{rps}</strong></td><td><strong>{srps}</strong></td>"
        f"<td><strong>{avg:,.0f} ms</strong></td></tr>"
    )

    if duration_s is not None:
        m, sec = divmod(int(duration_s), 60)
        d_str = f"{m}m {sec:02d}s" if m else f"{sec}s"
        dur_note = (
            f" &nbsp;<span style='font-weight:400;font-size:.8rem;color:#666'>"
            f"test duration: {d_str}</span>"
        )
    else:
        dur_note = ""

    return (
        "<section>"
        f'<div class="section-title" style="border-left-color:#0891b2;background:#ecfeff;">'
        f"Throughput Breakdown{dur_note}</div>"
        "<div class='table-wrap'>"
        "<table class='tp-tbl'>"
        "<thead><tr>"
        "<th>Section</th><th>Total Req</th><th>Successful</th>"
        "<th>Failed</th><th>Req/s</th><th>Success Req/s</th><th>Avg Response</th>"
        f"</tr></thead><tbody>{tbody}</tbody></table></div>"
        "<p style='font-size:.78rem;color:#666;margin-top:8px'>"
        "Req/s is averaged over the full test duration. Each section is only "
        "active during part of the run, so its actual load while active is higher."
        "</p></section>"
    )


def _critical_failures_section_html(all_data_rows: List[Dict]) -> str:
    """Return a highlighted section for endpoints above the failure/latency thresholds."""
    critical = []
    for row in all_data_rows:
        if row.get(_COL_NAME) == "Aggregated":
            continue
        try:
            total = int(row.get(_COL_REQS, 0) or 0)
            fails = int(row.get(_COL_FAILS, 0) or 0)
            avg   = float(row.get(_COL_AVG, 0) or 0)
            fp    = fails / total * 100 if total else 0.0
            if fp >= _CRIT_FAIL_PCT or avg >= _CRIT_AVG_MS:
                critical.append((row, fp, avg))
        except Exception:
            continue

    if not critical:
        return ""

    critical.sort(key=lambda x: (x[2], x[1]), reverse=True)

    tbody_rows = []
    for row, fp, avg_ms in critical:
        row_cls = "crit" if fp >= 100 or avg_ms >= _CRIT_AVG_MS else "warn"
        cells = []
        for header, col_key in _TABLE_HEADERS:
            if col_key is None:
                cells.append(f'<td class="fail">{fp:.1f} %</td>')
                continue
            raw = row.get(col_key, "") if col_key else ""
            if col_key == _COL_NAME:
                cells.append(f"<td class='name'>{raw}</td>")
            elif col_key in (_COL_REQS, _COL_FAILS):
                cells.append(f"<td>{_fmt(raw, 0)}</td>")
            else:
                cells.append(f"<td>{_fmt(raw)}</td>")
        tbody_rows.append(f'<tr class="{row_cls}">{"" .join(cells)}</tr>')

    count = len(critical)
    badge = f'<span class="badge critical">{count} endpoint{"s" if count != 1 else ""}</span>'
    thead = "".join(f"<th>{h}</th>" for h, _ in _TABLE_HEADERS)
    return (
        "<section>"
        f'<div class="section-title critical">Critical Issues {badge}</div>'
        "<div class='table-wrap'>"
        f"<table><thead><tr>{thead}</tr></thead>"
        f"<tbody>{''.join(tbody_rows)}</tbody></table></div></section>"
    )


