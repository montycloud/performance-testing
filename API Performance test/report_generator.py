def _build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="Generate a custom HTML performance report from Locust CSV stats.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument(
        "--csv",
        required=True,
        metavar="FILE",
        help="Path to the Locust stats CSV file (e.g. reports/stats_stats.csv)",
    )
    p.add_argument(
        "--output",
        default=None,
        metavar="FILE",
        help="Output HTML path (default: reports/custom_report_<timestamp>.html)",
    )
    return p


