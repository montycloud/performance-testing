def generate(
    stats_csv: Path,
    output: Optional[Path] = None,
    description: str = "",
    config_data: Optional[Dict] = None,
    report_name: str = "",
) -> Path:
    """
    Parse *stats_csv* and write a custom HTML report.

    Parameters
    ----------
    stats_csv:
        Path to the Locust ``<prefix>_stats.csv`` file.
    output:
        Explicit output path.  If *None*, a timestamped file is created under
        the ``reports/`` sub-directory next to this script.
    description:
        Human-readable test description shown in the report header.
    config_data:
        Full config dict (from config.yaml) to render in the config section.
    report_name:
        Custom name segment; output file becomes ``custom_<report_name>_<ts>.html``.
        Falls back to ``custom_report_<ts>.html`` when blank.

    Returns
    -------
    Path
        The path of the generated HTML file.
    """
    _REPORTS_DIR.mkdir(parents=True, exist_ok=True)

    if output is None:
        ts = datetime.now().strftime("%Y%m%d_%H%M%S")
        name_slug = report_name.strip() if report_name.strip() else "report"
        output = _REPORTS_DIR / f"custom_{name_slug}_{ts}.html"

    with open(stats_csv, newline="", encoding="utf-8") as fh:
        all_rows = list(csv.DictReader(fh))

    # Split rows by section prefix; keep the Aggregated row separately.
    aggregated_row: Optional[Dict] = None
    auth_rows: List[Dict] = []
    home_rows: List[Dict] = []
    wafr_rows: List[Dict] = []
    health_rows: List[Dict] = []
    chat_rows: List[Dict] = []

    for row in all_rows:
        name = row.get(_COL_NAME, "")
        if name == "Aggregated":
            aggregated_row = row
            continue
        if name.startswith("[Auth]"):
            auth_rows.append(row)
        elif name.startswith("[HomePage]"):
            home_rows.append(row)
        elif name.startswith("[WAFR]"):
            wafr_rows.append(row)
        elif name.startswith("[Health]"):
            health_rows.append(row)
        elif name.startswith("[Chat]"):
            chat_rows.append(row)
        # rows with unknown prefixes are silently ignored

    generated_at = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    html = _full_html(
        generated_at, stats_csv, auth_rows, home_rows, wafr_rows, health_rows, chat_rows,
        aggregated_row,
        description=description,
        config_data=config_data,
    )
    output.write_text(html, encoding="utf-8")
    return output


